def merge(existing, additions):
    by_date = {}
    for e in existing:
        by_date.setdefault(e["date"], []).append(e)
    for date, title, desc, tag, year in additions:
        e = {"date": date, "title": title, "desc": desc, "tag": tag}
        if year:
            e["year"] = year
        by_date.setdefault(date, []).append(e)
    out = []
    for d in sorted(by_date):
        out.extend(by_date[d])
    return out

def check_full_coverage(items):
    """校验 366 天全覆盖（含闰日 02-29）"""
    import datetime
    cov = set(e["date"] for e in items)
    missing = []
    for m in range(1, 13):
        days = 29 if m == 2 else (30 if m in (4, 6, 9, 11) else 31)
        for d in range(1, days + 1):
            k = f"{m:02d}-{d:02d}"
            if k not in cov:
                missing.append(k)
    return missing

