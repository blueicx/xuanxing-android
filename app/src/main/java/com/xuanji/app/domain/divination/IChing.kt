    data class HexagramInfo(
        val name: String, val judgement: String, val image: String, val interpretation: String
    )

    fun shake(date: LocalDate = LocalDate.now()): IChingResult {
        // 日期种子生成 6 爻（确定性）
        val seed = date.year * 372 + date.monthValue * 31 + date.dayOfMonth
        val values = (0 until 6).map { i ->
            val v = (seed / (i + 1) + i * 7919) % 4
            when (v) {
                0 -> 6
                1 -> 7
                2 -> 8
                else -> 9
            }
        }
        var binary = 0
        values.forEachIndexed { i, v -> if (v == 7 || v == 9) binary = binary or (1 shl i) }
        val num = ((binary % 64) + 64) % 64
        val info = HEXAGRAM_DATA[num] ?: HexagramInfo(
            "第${num + 1}卦", "卦辞未详，宜以变通之心领会。", "象辞未详。",
            "总评：此卦所示仅为当下时机之象，需结合自身处境灵活领会。\n事业：宜审时度势、稳中求进，不宜盲目冒进。\n财运：财来财去须有节制，量力而行、忌贪多务得。\n感情：顺其自然、真诚以待，莫强求亦莫轻弃。\n健康：作息有常、情志调和，注意防微杜渐。\n建议：静观其变、谋定后动，以平常心应万变。"
        )

        val lines = values.mapIndexed { i, v ->
            val label = when (v) {
                6 -> "老阴（变爻，将转阳）"
                7 -> "少阳（不变）"
                8 -> "少阴（不变）"
                else -> "老阳（变爻，将转阴）"
            }
            Line(i + 1, v, label)
        }
        val hexagramStr = lines.reversed().joinToString("\n") {
            if (it.value == 7 || it.value == 9) "━━━━━" else "━━ ━━"
        }

        return IChingResult(
            date = date,
            hexagramName = info.name,
            judgement = info.judgement,
            image = info.image,
            interpretation = info.interpretation,
            lines = lines,
            hexagramStr = hexagramStr
        )
    }
