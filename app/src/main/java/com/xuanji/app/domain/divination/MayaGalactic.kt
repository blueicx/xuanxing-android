data class MayaGalacticResult(
    val date: LocalDate,
    val kin: Int,
    val signIndex: Int,
    val toneIndex: Int,
    val signChinese: String,
    val signOriginal: String,
    val toneChinese: String,
    val color: String,
    val element: String,
    val fullSignature: String,
    val totems: Map<String, String>,   // main/support/challenge/guide/antipode -> 中文名
    val interpretation: MayaInterpretation,
    val verdict: String
)

// ======================== 核心计算 ========================

object MayaGalactic {

    /** KIN 值（1-260） */
    fun kin(date: LocalDate): Int {
        val base = LocalDate.of(2000, 1, 1)
        val delta = ChronoUnit.DAYS.between(base, date)
        val k = (35 + delta) % 260
        return if (k == 0L) 260 else k.toInt()
    }

    /** 完整结果 */
    fun calculate(date: LocalDate): MayaGalacticResult {
        val k = kin(date)
        val kinZero = k - 1
        val signIdx = kinZero % 20
        val toneIdx = kinZero % 13
        val sign = MAYA_DAY_SIGNS[signIdx]
        val tone = MAYA_TONES[toneIdx]

        // 五大天赋图腾（1-20 序号）
        val signNum = signIdx + 1
        val main = signNum
        val support = (signNum % 20) + 1
        val challenge = ((signNum + 9) % 20) + 1
        val guide = (21 - signNum) % 20
        val guideNum = if (guide == 0) 20 else guide
        val antipode = ((signNum + 9) % 20) + 1

        fun name(num: Int): String = MAYA_DAY_SIGNS[num - 1].chinese
        val totems = mapOf(
            "main" to name(main), "support" to name(support), "challenge" to name(challenge),
            "guide" to name(guideNum), "antipode" to name(antipode)
        )
        val base = MayaGalacticResult(
            date, k, signIdx, toneIdx, sign.chinese, sign.original, tone.chinese,
            COLOR_MAP[sign.chinese] ?: "未知", ELEMENT_MAP[sign.chinese] ?: "未知",
            "${tone.chinese}的${sign.chinese}",
            totems,
            SIGN_INTERPRETATIONS[sign.chinese] ?: MayaInterpretation("", "", "", "", ""),
            ""
        )
        return base.copy(verdict = buildVerdict(base))
    }

    /** 由主图腾六维 + 音阶 + 五大天赋图腾合成解读 */
    private fun buildVerdict(r: MayaGalacticResult): String {
        val dims = GALACTIC_VERDICTS[r.signChinese] ?: return ""
        val support = r.totems["support"] ?: ""
        val challenge = r.totems["challenge"] ?: ""
        val guide = r.totems["guide"] ?: ""
        val antipode = r.totems["antipode"] ?: ""
        return buildString {
            appendLine("总评：${dims[0]}此印记以「${r.toneChinese}音阶」运行，与指引图腾${guide}的能量遥相呼应。")
            appendLine("事业：${dims[1]}")
            appendLine("财运：${dims[2]}支持图腾${support}提示你，善用资源与人脉能让财路更顺。")
            appendLine("感情：${dims[3]}")
            appendLine("健康：${dims[4]}")
            append("建议：${dims[5]}挑战图腾${challenge}正是此阶段要跨越的课题，推动图腾${antipode}则为你点燃潜能。")
        }
    }
}
