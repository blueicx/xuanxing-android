    ): List<HermesLot> {
        fun pos(name: String): Double = when (name) {
            "ASC" -> asc
            "太阳" -> sun
            "月亮" -> moon
            else -> planets[name] ?: 0.0
        }
        return HERMETIC_LOTS.map { (name, pair) ->
            val (aName, bName) = pair
            val a = pos(aName)
            val b = pos(bName)
            val raw = if (isDiurnal) asc + a - b else asc + b - a
            val deg = norm(raw)
            val sign = SIGNS[(deg / 30).toInt() % 12]
            val base = LOT_INTERPRETATION[name] ?: "此点反映个人在相关领域的潜能。"
            HermesLot(name, deg, sign, "$base 位于 ${sign}座 ${"%.1f".format(deg % 30)}°。")
        }
    }

    /** 灵性指引（六维解读） */
    fun guidance(fortuneSign: String): String {
        val dims = SIGN_VERDICTS[fortuneSign]
            ?: return "总评：您的幸运领域尚待星图确认，请稍后再试。"
        return dims.joinToString("\n")
    }
}
