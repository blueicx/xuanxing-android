    /** 长纪历（Long Count）：二十进制变体，以天为最小单位逐级进位。 */
    data class LongCount(
        val baktun: Int,   // 巴克顿：144000 天
        val katun: Int,    // 卡盾：7200 天
        val tun: Int,      // 盾：360 天
        val uinal: Int,    // 乌纳尔：20 天
        val kin: Int,      // 金：1 天
        val totalDays: Long
    ) {
        val label: String get() = "$baktun.$katun.$tun.$uinal.$kin"
    }

    // GMT 相关常数：长纪历 0.0.0.0.0 = 儒略日 584283（公历 3114-08-11 proleptic）。
    // 2012-12-21 为 13.0.0.0.0（= 13 巴克顿 = 1872000 天），故 JDN(2012-12-21) = 2456283，吻合。
    private const val GMT_CORRELATION = 584283L
    // 1970-01-01 的儒略日（toEpochDay 的基准）。
    private const val JDN_1970 = 2440588L

    /** 由公历日期求长纪历 */
    fun longCountForDate(date: LocalDate): LongCount {
        val jdn = date.toEpochDay() + JDN_1970
        val days = jdn - GMT_CORRELATION   // 自长纪历 0.0.0.0.0 起的天数（受支持日期均为正）
        val baktun = (days / 144000L).toInt()
        var rem = days % 144000L
        val katun = (rem / 7200L).toInt()
        rem %= 7200L
        val tun = (rem / 360L).toInt()
        rem %= 360L
        val uinal = (rem / 20L).toInt()
        val kin = (rem % 20L).toInt()
        return LongCount(baktun, katun, tun, uinal, kin, days)
    }

    private val ANCHOR = LocalDate.of(2000, 1, 1) // 13 Ahau (nameIdx=19), Haab 18 Cumku

    fun forDate(date: LocalDate): MayaResult {
        val days = date.toEpochDay() - ANCHOR.toEpochDay()
        val number = (((days + 12) % 13 + 13) % 13 + 1).toInt()
        val nameIdx = (((days + 19) % 20 + 20) % 20).toInt()
        val haabDay = (((357 + days) % 365 + 365) % 365).toInt()
        val haab = if (haabDay >= 360) {
            HaabDate("Wayeb", (haabDay - 360))
        } else {
            HaabDate(HAAB_MONTHS[haabDay / 20], haabDay % 20)
        }
        val tzolkin = TzolkinDate(number, nameIdx, DAY_NAMES[nameIdx], DAY_NAMES_CN[nameIdx])
        return MayaResult(
            tzolkin,
            haab,
            longCountForDate(date),
            "${number} ${DAY_NAMES[nameIdx]} · ${haab.month} ${haab.day} · ${longCountForDate(date).label}",
            buildVerdict(tzolkin)
        )
    }

    /** 由 20 图腾 + 13 音阶合成六维解读 */
    private fun buildVerdict(tzolkin: TzolkinDate): String {
        val dims = TOTEM_VERDICTS[tzolkin.nameIdx]
        val tone = TONE_NAMES.getOrNull(tzolkin.number - 1) ?: ""
        val toneMean = TONE_MEANINGS.getOrNull(tzolkin.number - 1) ?: ""
        if (dims == null) return ""
        return buildString {
            appendLine("总评：${dims[0]}今日处于${tone}音阶（${toneMean}），图腾与音阶的能量相叠，正是你此刻运势的底色。")
            appendLine("事业：${dims[1]}")
            appendLine("财运：${dims[2]}")
            appendLine("感情：${dims[3]}")
            appendLine("健康：${dims[4]}")
            append("建议：${dims[5]}")
        }
    }

    fun forProfile(profile: UserProfile): MayaResult =
        forDate(LocalDate.of(profile.birthYear, profile.birthMonth, profile.birthDay))
