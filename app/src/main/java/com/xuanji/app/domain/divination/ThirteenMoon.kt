    /** 计算星系印记 */
    fun cast(birthDate: LocalDate): ThirteenMoonResult {
        var year = birthDate.year
        var month = birthDate.monthValue
        var day = birthDate.dayOfMonth
        // 2 月 29 日简化按 2 月 28 日处理
        if (month == 2 && day == 29) day = 28

        val yearVal = YEAR_VALUES[year] ?: 0
        val monthVal = MONTH_VALUES[month] ?: 0
        var kin = yearVal + monthVal + day
        while (kin > 260) kin -= 260
        if (kin <= 0) kin += 260

        val kinZero = kin - 1
        val signIdx = kinZero % 20
        val toneIdx = kinZero % 13
        val sign = SIGNS[signIdx]
        val tone = TONES[toneIdx]
        val color = COLOR_MAP[sign] ?: "未知"
        val toneInfo = TONE_INFO.getValue(tone)
        val signInfo = SIGN_INFO.getValue(sign)
        // 嵌套 Pair 解构：(关键词 to (性格 to (天赋 to (挑战 to 指引))))
        val signKeyword = signInfo.first
        val personality = signInfo.second.first
        val talent = signInfo.second.second.first
        val challenge = signInfo.second.second.second.first
        val guidance = signInfo.second.second.second.second

        // 出生波符：13 调性，图腾依次推进
        val wave = (0 until 13).map { i ->
            val t = TONES[i]
            val s = SIGNS[(signIdx + i) % 20]
            val info = TONE_INFO.getValue(t)
            WavePoint(t, s, info.first, info.second)
        }

        // 五大天赋力量
        val signNum = signIdx + 1
        val main = signNum
        val support = (signNum % 20) + 1
        val challengeNum = ((signNum + 9) % 20) + 1
        var guide = (21 - signNum) % 20
        if (guide == 0) guide = 20
        val antipode = ((signNum + 9) % 20) + 1
        val nameOf = { n: Int -> SIGNS[n - 1] }
        val totems = linkedMapOf(
            "主图腾" to Totem(main, nameOf(main)),
            "支持图腾" to Totem(support, nameOf(support)),
            "挑战图腾" to Totem(challengeNum, nameOf(challengeNum)),
            "推动图腾" to Totem(guide, nameOf(guide)),
            "指引图腾" to Totem(antipode, nameOf(antipode))
        )

        val verdict = buildVerdict(
            sign, tone, toneInfo.first, toneInfo.second,
            personality, talent, challenge, guidance, totems
        )

        return ThirteenMoonResult(
            date = birthDate,
            kin = kin,
            tone = tone,
            sign = sign,
            color = color,
            toneKeyword = toneInfo.first,
            toneQuestion = toneInfo.second,
            signKeyword = signKeyword,
            personality = personality,
            talent = talent,
            challenge = challenge,
            guidance = guidance,
            verdict = verdict,
            wave = wave,
            totems = totems
        )
    }

    /** 六维解读：总评 + 事业/财运/感情/健康/建议，贴合 Kin 印记（调性 × 图腾）主题 */
    private fun buildVerdict(
        sign: String,
        tone: String,
        toneKeyword: String,
        toneQuestion: String,
        personality: String,
        talent: String,
        challenge: String,
        guidance: String,
        totems: Map<String, Totem>
    ): String {
        val support = totems["支持图腾"]?.name ?: "红龙"
        val guide = totems["推动图腾"]?.name ?: "红龙"
        val wealth = SIGN_WEALTH[sign] ?: "以沉稳的态度累积资源，善用天赋自会聚财"
        val love = SIGN_LOVE[sign] ?: "以真诚相待，关系自会温暖而长久"
        val health = SIGN_HEALTH[sign] ?: "留意作息与情绪的平衡，身心自会安泰"
        val sb = StringBuilder()
        sb.append("总评：你的星系印记是「${tone}的$sign」，调性关键词为「$toneKeyword」，此生围绕「$toneQuestion」展开；$personality")
        sb.append("\n事业：以「$tone」的节奏推进工作，$sign 的「$talent」是你最可倚仗的职场天赋，顺势而为胜于强求")
        sb.append("\n财运：$wealth；配合「$support」的支持图腾之助，让资源循专注与付出自然聚拢")
        sb.append("\n感情：$love；「$guide」的推动图腾提示你在关系里适时迈出主动的一步")
        sb.append("\n健康：$health，让身体跟上你调性里的能量节拍")
        sb.append("\n建议：留意「$challenge」，$guidance")
        return sb.toString()
    }
