    fun analyze(
        forehead: String, eyes: String, nose: String, mouth: String, chin: String
    ): PhysiognomyResult {
        val features = linkedMapOf(
            "额头" to forehead, "眼睛" to eyes, "鼻子" to nose,
            "嘴巴" to mouth, "下巴" to chin
        )
        val interpretations = features.mapValues { (part, desc) ->
            INTERPRETATIONS[part]?.get(desc) ?: "特征未详，需面诊。"
        }

        val summary = when {
            "饱满" in forehead && "大而有神" in eyes && "高挺" in nose ->
                "您具有卓越的领导潜质和智慧，人生路较顺畅，适合担任管理或开创性工作。"
            "窄小" in forehead && "细长" in eyes ->
                "您思想深邃，但早年需多奋斗，中年后运势上升，宜从事研究或技术类职业。"
            else ->
                "您的面相综合显示为平和稳重，人际关系良好，一生平顺，适合稳定发展。"
        }
        return PhysiognomyResult(features, interpretations, summary)
    }

    /** 取单个部位某一选项的具体解读（供 UI 内联展示）。 */
    fun interpretFeature(feature: String, option: String): String =
        INTERPRETATIONS[feature]?.get(option) ?: "特征未详，需面诊。"
