// ======================== 结果模型 ========================

data class TajulResult(
    val husbandName: String,
    val wifeName: String,
    val husbandArabic: String,
    val wifeArabic: String,
    val husbandSum: Int,
    val wifeSum: Int,
    val husbandRemainder: Int,  // 1..7（0 视为 7）
    val wifeRemainder: Int,
    val interpretation: TajulInterpretation
)

// ======================== 核心计算 ========================

object TajulMuluk {

    /** 姓名 → 阿拉伯字母序列（已是阿拉伯文则原样返回，否则拉丁映射） */
    fun toArabic(name: String): String {
        if (name.any { it in '\u0600'..'\u06FF' }) return name
        val sb = StringBuilder()
        for (ch in name.lowercase()) {
            LATIN_TO_ARABIC[ch]?.let { sb.append(it) }
        }
        return sb.toString()
    }

    /** Abjadiyyah 数值和 */
    fun abjadSum(arabic: String): Int = arabic.sumOf { ABJAD_MAP[it] ?: 0 }

    /** 合婚计算 */
    fun compute(husbandName: String, wifeName: String): TajulResult {
        val hAr = toArabic(husbandName.trim())
        val wAr = toArabic(wifeName.trim())
        val hSum = abjadSum(hAr)
        val wSum = abjadSum(wAr)
        var hRem = hSum % 7
        var wRem = wSum % 7
        if (hRem == 0) hRem = 7
        if (wRem == 0) wRem = 7
        val interp = INTERPRETATION_TABLE[hRem to wRem] ?: DEFAULT_INTERPRETATION
        return TajulResult(
            husbandName = husbandName.trim(),
            wifeName = wifeName.trim(),
            husbandArabic = hAr,
            wifeArabic = wAr,
            husbandSum = hSum,
            wifeSum = wSum,
            husbandRemainder = hRem,
            wifeRemainder = wRem,
            interpretation = interp
        )
    }
}
