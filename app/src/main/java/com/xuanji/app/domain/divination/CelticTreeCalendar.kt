// ======================== 核心计算 ========================

object CelticTreeCalendar {

    /** 按日期取树月（12/23 无名日） */
    fun treeSign(date: LocalDate): CelticTreeResult {
        val m = date.monthValue
        val d = date.dayOfMonth
        if (m == 12 && d == 23) {
            return CelticTreeResult(date, true, "无名日 (Nameless Day)", "—", "—", "—",
                "12 月 23 日是凯尔特树历中神秘的无名日，不属于任何月份。这是一个超越时间、适合反思和灵性探索的日子。", "", "", "",
                NAMELESS_VERDICT.joinVerdict())
        }
        val tm = TREE_MONTHS.firstOrNull { tm ->
            val crossesYear = tm.startM > tm.endM || (tm.startM == tm.endM && tm.startD > tm.endD)
            if (crossesYear) (m == tm.startM && d >= tm.startD) || (m == tm.endM && d <= tm.endD)
            else (m == tm.startM && d >= tm.startD) || (m == tm.endM && d <= tm.endD) && (tm.startM <= m && m <= tm.endM)
        }
        val info = tm?.let { TREE_INTERPRETATIONS[it.name] }
        return CelticTreeResult(
            date, false, tm?.name ?: "未知", tm?.ogham ?: "—", tm?.element ?: "—", tm?.animal ?: "—",
            info?.personality ?: "", info?.fate ?: "", info?.guidance ?: "", info?.luckyColor ?: "",
            TREE_VERDICTS[tm?.name]?.joinVerdict() ?: ""
        )
    }

    /** 13 树月一览 */
    fun treeTable(): List<Triple<String, String, String>> =
        TREE_MONTHS.map { Triple(it.name, it.ogham, "${it.element} / ${it.animal}") }
}
