// ======================== 核心计算 ========================

object MedicineWheel {

    /** 按出生月份定位方向 */
    fun directionFor(date: LocalDate): MedicineWheelDirection {
        val month = date.monthValue
        return MEDICINE_WHEEL_DIRECTIONS.firstOrNull { d ->
            if (d.startMonth > d.endMonth) month >= d.startMonth || month <= d.endMonth
            else month in d.startMonth..d.endMonth
        } ?: MEDICINE_WHEEL_DIRECTIONS[0]
    }
}
