data class AztecResult(
    val date: LocalDate,
    val signIndex: Int,
    val number: Int,
    val signChinese: String,
    val signEnglish: String,
    val god: String,
    val direction: String,
    val fullSignature: String,
    val interpretation: AztecInterpretation,
    val verdict: String
)

// ======================== 核心计算 ========================

object AztecAstrology {

    private val ANCHOR_JD = 2276827.5
    private val ANCHOR_SIGN_INDEX = 4   // Coatl 蛇
    private val ANCHOR_NUMBER = 1

    private fun dateToJd(dt: LocalDate): Double {
        var y = dt.year; var m = dt.monthValue
        if (m <= 2) { y -= 1; m += 12 }
        val a = y / 100
        val b = 2 - a + a / 4
        return (365.25 * (y + 4716)).toLong() + (30.6001 * (m + 1)).toLong() + dt.dayOfMonth + b - 1524.5
    }

    /** 完整结果 */
    fun calculate(date: LocalDate): AztecResult {
        val jd = dateToJd(date)
        val daysDiff = (jd - ANCHOR_JD).roundToInt()
        val signIdx = ((ANCHOR_SIGN_INDEX + daysDiff) % 20 + 20) % 20
        val number = (((ANCHOR_NUMBER - 1) + daysDiff) % 13 + 13) % 13 + 1
        val sign = AZTEC_DAY_SIGNS[signIdx]
        val god = SIGN_GOD[sign.chinese] ?: "未知"
        val direction = SIGN_DIRECTION[sign.chinese] ?: "未知"
        val base = AztecResult(
            date, signIdx, number, sign.chinese, sign.english,
            god, direction,
            "$number ${sign.chinese}",
            SIGN_INTERPRETATIONS[sign.chinese] ?: AztecInterpretation("", "", "", "", ""),
            ""
        )
        return base.copy(verdict = buildVerdict(base))
    }

    /** 由 20 日符六维 + 数字 + 方位/守护神合成解读 */
    private fun buildVerdict(r: AztecResult): String {
        val dims = AZTEC_VERDICTS[r.signChinese] ?: return ""
        return buildString {
            appendLine("总评：${dims[0]}数字${r.number}标记着此印记的能量强度，方位在${r.direction}，由${r.god}守护。")
            appendLine("事业：${dims[1]}")
            appendLine("财运：${dims[2]}")
            appendLine("感情：${dims[3]}")
            appendLine("健康：${dims[4]}")
            append("建议：${dims[5]}")
        }
    }
}
