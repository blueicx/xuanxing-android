    private fun verdictFor(rune: RuneItem, reversed: Boolean): String {
        val dims = RUNE_VERDICTS[rune.name] ?: return rune.upright
        val head = if (reversed) "【逆位】此符倒置，能量受阻，以下六维宜作警示与内省，慢即是快。\n"
        else "【正位】此符顺位而立，能量流动顺畅，以下六维可作为当下运势的注脚。\n"
        val labels = listOf("总评：", "事业：", "财运：", "感情：", "健康：", "建议：")
        val body = dims.zip(labels).joinToString("\n") { (line, label) -> label + line }
        return head + body
    }

