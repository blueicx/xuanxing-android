    private fun interpretation(code: String): String {
        val i = HOUSE_INFO[code]!!
        return "学院名：${HOUSE_NAMES[code]!!}\n" +
            "代表色：${i.color}\n" +
            "学院动物：${i.animal}\n" +
            "创始人：${i.founder}\n" +
            "核心特质：${i.traits}\n" +
            "核心价值观：${i.values}\n" +
            "知名校友：${i.alumni}\n" +
            "学院名言：${i.motto}\n" +
            "适合职业：${i.career}\n" +
