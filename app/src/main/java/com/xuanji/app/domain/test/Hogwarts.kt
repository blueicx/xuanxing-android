    /** 每题四选项分别代表四学院，rot 用于轮换字母位置，避免答案集中于固定字母 */
    private fun hwq(text: String, g: String, r: String, h: String, s: String, rot: Int): HogwartsQuestion {
        val houses = listOf("G" to g, "R" to r, "H" to h, "S" to s)
        val shift = rot % 4
        val shifted = houses.drop(shift) + houses.take(shift)
        val letters = listOf("A", "B", "C", "D")
        val options = letters.zip(shifted.map { it.second })
        val weights = letters.zip(shifted.map { it.first }).toMap()
        return HogwartsQuestion(text, options, weights)
    }

