    }

    private fun buildPortrait(scores: Map<String, Int>, houseCode: String): String {
        val detail = HOUSE_ORDER.joinToString("，") { "${HOUSE_NAMES[it]!!} ${scores[it]!!} 分" }
        return "你的四学院得分为 ${detail}，总分最高的是 ${HOUSE_NAMES[houseCode]!!}。" +
            "分院帽看重的不是你最像谁，而是你最看重什么。" +
            "无论身在哪个学院，勇敢、智慧、忠诚与野心都值得被珍视，愿你带着这些品质在自己的人生里闪闪发光。"
    }

    /** 计分：answers 为每题所选选项字母（A/B/C/D） */
    fun calculate(answers: List<String>): HogwartsResult {
        val scores = mutableMapOf("G" to 0, "R" to 0, "H" to 0, "S" to 0)
        QUESTIONS.forEachIndexed { i, q ->
            val letter = answers.getOrNull(i) ?: return@forEachIndexed
            val house = q.weights[letter] ?: return@forEachIndexed
            scores[house] = scores.getOrDefault(house, 0) + 1
        }
        // 取最高分学院：分数降序，并列时按 HOUSE_ORDER（G/R/H/S）顺序取先出现的，确定性
        val houseCode = HOUSE_ORDER
            .map { it to scores[it]!! }
            .sortedWith(
                compareByDescending<Pair<String, Int>> { it.second }
                    .thenBy { HOUSE_ORDER.indexOf(it.first) }
            )
            .first().first
        return HogwartsResult(
            scores = scores,
            houseCode = houseCode,
            houseName = HOUSE_NAMES[houseCode]!!,
            interpretation = interpretation(houseCode),
            portrait = buildPortrait(scores, houseCode)
        )
    }
