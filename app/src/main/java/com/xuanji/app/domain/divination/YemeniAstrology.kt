// ======================== 结果模型 ========================

data class YemeniResult(
    val date: LocalDate,
    val sunLongitude: Double,
    val signIndex: Int,
    val sign: String,
    val symbol: String,
    val element: String,
    val quality: String,
    val polarity: String,
    val subRuler: String,
    val personality: String,
    val fate: String,
    val verdict: String
)

// ======================== 核心计算 ========================

object YemeniAstrology {

    private fun dateToJd(dt: LocalDate): Double {
        var y = dt.year; var m = dt.monthValue
        if (m <= 2) { y -= 1; m += 12 }
        val a = y / 100
        val b = 2 - a + a / 4
        return (365.25 * (y + 4716)).toLong() + (30.6001 * (m + 1)).toLong() + dt.dayOfMonth + b - 1524.5
    }

    /** 太阳黄经（Jean Meeus 简化） */
    fun sunLongitude(date: LocalDate): Double {
        val days = dateToJd(date) - 2451545.0
        val meanLon = (280.46646 + 0.98564736 * days) % 360
        val meanAnom = Math.toRadians((357.52911 + 0.98560028 * days) % 360)
        val c = 1.914602 * sin(meanAnom) + 0.019993 * sin(2 * meanAnom) + 0.000289 * sin(3 * meanAnom)
        return ((meanLon + c) % 360 + 360) % 360
    }

    /** 完整结果 */
    fun calculate(date: LocalDate): YemeniResult {
        val lon = sunLongitude(date)
        val idx = floor(lon / 30).toInt() % 12
        val sign = ZODIAC_SIGNS[idx]
        val info = SIGN_INTERPRETATION[sign] ?: SignInfo("", "")
        val dims = SIGN_VERDICT[sign] ?: emptyList()
        val verdict = if (dims.size >= 6) dims.joinToString("") + "（也门占星为南阿拉伯星学遗产，结果仅供文化娱乐参考）" else ""
        return YemeniResult(
            date = date,
            sunLongitude = lon,
            signIndex = idx,
            sign = sign,
            symbol = ZODIAC_SYMBOLS[idx],
            element = ELEMENT_MAP[sign] ?: "",
            quality = QUALITY_MAP[sign] ?: "",
            polarity = POLARITY_MAP[sign] ?: "",
            subRuler = SUB_RULER_MAP[sign] ?: "",
            personality = info.personality,
            fate = info.fate,
            verdict = verdict
        )
    }

    /** 12 星宫一览 */
    fun signTable(): List<YemeniResult> =
        ZODIAC_SIGNS.indices.map { idx ->
            val sign = ZODIAC_SIGNS[idx]
            val dims = SIGN_VERDICT[sign] ?: emptyList()
            YemeniResult(LocalDate.now(), idx * 30.0, idx, sign, ZODIAC_SYMBOLS[idx],
                ELEMENT_MAP[sign] ?: "", QUALITY_MAP[sign] ?: "",
                POLARITY_MAP[sign] ?: "", SUB_RULER_MAP[sign] ?: "",
                SIGN_INTERPRETATION[sign]?.personality ?: "", SIGN_INTERPRETATION[sign]?.fate ?: "",
                if (dims.size >= 6) dims.joinToString("") + "（也门占星为南阿拉伯星学遗产，结果仅供文化娱乐参考）" else "")
        }
}
