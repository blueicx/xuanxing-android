    /** 当日同月同日生的名人（确定性） */
    fun forToday(date: LocalDate = LocalDate.now()): List<Figure> {
        val md = date.format(DateTimeFormatter.ofPattern("MM-dd"))
        val matched = FIGURES.filter { it.date == md }
        if (matched.isNotEmpty()) return matched
        // 无匹配：按年内第几天确定性挑 2 位展示
        val dayHash = date.dayOfYear
        return (0 until FIGURES.size)
            .map { FIGURES[(it * 7 + dayHash) % FIGURES.size] }
            .distinctBy { it.date }
            .take(2)
    }
