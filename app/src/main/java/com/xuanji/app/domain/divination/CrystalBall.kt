    fun gaze(date: LocalDate = LocalDate.now(), seedOffset: Int = 0): CrystalResult {
        val seed = date.year * 372 + date.monthValue * 31 + date.dayOfMonth + seedOffset * 7919
        val reading = SYMBOLS[((seed % SYMBOLS.size) + SYMBOLS.size) % SYMBOLS.size]
        return CrystalResult(reading.symbol, reading.meaning, reading.verdict, date)
    }
