    fun calculate(profile: UserProfile): List<NumberItem> {
        val y = profile.birthYear
        val m = profile.birthMonth
        val d = profile.birthDay

        val lifePath = reduce(y / 1000 + (y / 100) % 10 + (y / 10) % 10 + y % 10 + digitSum(m) + digitSum(d))
        val talent = reduce(digitSum(y))            // 先天/天赋：年
        val expression = reduce(digitSum(m) + digitSum(d)) // 后天/实现：月日
        val birthday = reduce(d)                    // 生日数

        return listOf(
            NumberItem("生命数字", lifePath, lifePath >= 11, TRAITS[lifePath] ?: "", NUMBER_VERDICTS[lifePath] ?: ""),
            NumberItem("天赋数字", talent, talent >= 11, TRAITS[talent] ?: "", NUMBER_VERDICTS[talent] ?: ""),
            NumberItem("实现数字", expression, expression >= 11, TRAITS[expression] ?: "", NUMBER_VERDICTS[expression] ?: ""),
            NumberItem("生日数字", birthday, birthday >= 11, TRAITS[birthday] ?: "", NUMBER_VERDICTS[birthday] ?: "")
        )
    }

    private fun digitSum(n: Int): Int = n.toString().sumOf { it.digitToInt() }

    /** 累减至 1-9，保留 11/22/33 大师数 */
    private fun reduce(n: Int): Int {
        var v = n
        while (v > 9 && v != 11 && v != 22 && v != 33) {
            v = v.toString().sumOf { it.digitToInt() }
        }
        return v
    }

