const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.join(__dirname, '..');
const gradle = fs.readFileSync(path.join(root, 'app/build.gradle.kts'), 'utf8');
assert(gradle.includes('applicationIdSuffix = ".regression"'), 'process recovery must use a separate app data directory');
assert(gradle.includes('xuanjiRegression'), 'normal debug must remain the default instrumentation target');
const scriptPath = path.join(root, '_dev/isolated_application_recovery.js');
assert(fs.existsSync(scriptPath), 'emulator-only process-recovery runner is required');
const script = fs.readFileSync(scriptPath, 'utf8');
assert(script.includes('ro.kernel.qemu') && script.includes('metadata.applicationId !== expected'));
assert(script.includes("const pkg = 'com.xuanji.app.regression'") && script.includes("'force-stop', pkg"));
assert(!script.includes("'uninstall'") && !script.includes("'pm', 'clear'"), 'runner must not erase app data');
const workflow = fs.readFileSync(path.join(root, '.github/workflows/build.yml'), 'utf8');
assert(workflow.includes('node _dev/application_recovery_contract_test.js'), 'CI must include isolation contract');
assert(workflow.includes('node _dev/isolated_application_recovery.js --auto'), 'CI must execute actual process restart');
const journey = fs.readFileSync(path.join(root, 'app/src/androidTest/kotlin/com/xuanji/app/ui/ApplicationRecoveryJourneyTest.kt'), 'utf8');
assert(journey.includes('不要豆腐，只有十五分钟') && journey.includes('sendInput("第二个")') && journey.includes('sendInput("为什么")'));
assert(journey.includes('Assert.assertEquals(foodPreferenceBefore') && journey.includes('restored.referenceId'), 'real journey must verify memory boundary and recovered reference');
assert(script.includes("phase('four_roles_handoff_and_independent_game_progress_use_real_application')"));
assert(journey.includes('secondFixture') && journey.includes('GameArchiveStore(context).load(visit)'));
assert(fs.existsSync(path.join(root, '_dev/isolated_memory_sampler.js')), 'real application memory sampler is missing');
const sampler = fs.readFileSync(path.join(root,'_dev/isolated_memory_sampler.js'),'utf8');
assert(sampler.includes('fs.renameSync'), 'memory snapshots must be atomically published to concurrent readers');
const guide = fs.readFileSync(path.join(root, 'app/src/main/java/com/xuanji/app/ui/components/MysticGuideCard.kt'), 'utf8');
assert(!guide.includes('sessionState = MysticSessionState()'), 'thread clear must invalidate old request tokens, not reset them to zero');
assert(guide.includes('fun resetCurrentThread()') && guide.includes('onClick = ::resetCurrentThread'), 'restart and clear must share the same reducer-backed action');
assert(!guide.includes('private val mysticCompanionStates'), 'closed scopes must not revive threads after local data deletion');
const scopeTest = fs.readFileSync(path.join(root, 'app/src/test/kotlin/com/xuanji/app/ui/components/MysticCompanionScopeTest.kt'), 'utf8');
assert(scopeTest.includes('assertNotSame('), 'fresh companion scope requires a behavioral JVM regression');
console.log('Application recovery isolation contract PASS');
